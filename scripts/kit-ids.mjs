// Writes tour/kit-ids.js: each self-hosted kit's part keys and the Polyfork catalogue ids they stand for. A kit folder
// names its parts by key (tunnel-portal.mjs); Polyfork's CDN names them by id (tunnel-portal-4ac9f3.mjs). With the kits
// built from the account CDN (config.js KIT_CDN, as on the published site, which has no kits/ folder) the tour finds a
// part by its key through this table. Every part of every kit is listed, placed in its kit's layout or not, so any key a
// kit has resolves. The ids are public (each is the part's page on polyfork.dev); the kits themselves stay uncommitted.
//
//   node scripts/kit-ids.mjs [kits folder, default ./kits]
//
// Run it again after adding a kit or updating one.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { KITS } from '../tour/config.js';

const root = process.argv[2] ?? 'kits';
const ASSET = /https:\/\/polyfork\.dev\/asset\/([a-z0-9-]+)/;

const table = {};
for (const kit of Object.values(KITS)) {
  const dir = join(root, kit);
  if (!existsSync(dir)) throw new Error(`no kit folder ${dir}`);
  const keys = Object.keys(JSON.parse(readFileSync(join(dir, 'PARTS.json'), 'utf8')));
  const ids = {};
  for (const key of keys.filter((k) => k !== 'terrain').sort()) {   // (its ground comes with its layout)
    const file = join(dir, `${key}.mjs`);
    if (!existsSync(file)) { console.warn(`${kit}: no ${key}.mjs`); continue; }
    const id = readFileSync(file, 'utf8').slice(0, 2000).match(ASSET)?.[1];
    if (!id) { console.warn(`${kit}: ${key}.mjs names no asset id`); continue; }
    ids[key] = id;
  }
  table[kit] = ids;
  console.log(`${kit}: ${Object.keys(ids).length} of ${keys.length - (keys.includes('terrain') ? 1 : 0)} parts`);
}

const lines = Object.entries(table).map(([kit, ids]) => `  '${kit}': {\n${
  Object.entries(ids).map(([k, id]) => `    '${k}': '${id}',`).join('\n')}\n  },`);
writeFileSync('tour/kit-ids.js', `// Generated by scripts/kit-ids.mjs from the kits' own modules: each kit's part keys and their Polyfork catalogue ids,
// for building the kits from the account CDN (config.js kitUrl). Don't edit by hand; run the script again.
export const KIT_IDS = {
${lines.join('\n')}
};
`);
console.log('wrote tour/kit-ids.js');
